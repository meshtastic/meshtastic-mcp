"""Serve ``meshtastic.protobuf.*_pb2`` from protos generated here, ahead of the library's own.

The ``meshtastic`` releases trail ``meshtastic/protobufs`` by months, so the modules in
``generated/`` (regenerated by ``scripts/regen_protos.sh``, ref in ``generated/PROTOBUFS_REF``)
are what every ``meshtastic.protobuf`` import resolves to once :func:`install` has run.
"""

from __future__ import annotations

import importlib.abc
import importlib.machinery
import importlib.util
import sys
import warnings
from collections.abc import Sequence
from pathlib import Path
from types import ModuleType

GENERATED = Path(__file__).parent / "generated"
_PREFIX = "meshtastic.protobuf."


class _GeneratedProtos(importlib.abc.MetaPathFinder):
    def find_spec(
        self,
        fullname: str,
        path: Sequence[str] | None,
        target: ModuleType | None = None,
    ) -> importlib.machinery.ModuleSpec | None:
        leaf = fullname.removeprefix(_PREFIX)
        if leaf == fullname or "." in leaf or not leaf.endswith("_pb2"):
            return None
        source = GENERATED / f"{leaf}.py"
        if not source.is_file():
            return None
        return importlib.util.spec_from_file_location(fullname, source)


def install() -> bool:
    """Put the generated protos ahead of the library's; returns whether they are in use.

    Must run before anything imports ``meshtastic``: protobuf's descriptor pool refuses a
    second copy of a file, so once the library's own modules are loaded these stand aside.
    """
    if any(isinstance(finder, _GeneratedProtos) for finder in sys.meta_path):
        return True
    loaded = sorted(name for name in sys.modules if name.startswith(_PREFIX))
    if loaded:
        warnings.warn(
            f"{loaded[0]} was imported before meshtastic_mcp; using the meshtastic library's "
            "own protos, not meshtastic_mcp's",
            RuntimeWarning,
            stacklevel=2,
        )
        return False
    sys.meta_path.insert(0, _GeneratedProtos())
    return True


def protobufs_ref() -> str:
    """The meshtastic/protobufs commit the generated modules were built from."""
    return (GENERATED / "PROTOBUFS_REF").read_text().strip()
