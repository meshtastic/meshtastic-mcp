"""Generate the reference docs from the code.

`docs/tools.md`, the toolset tables in `README.md` and `docs/toolsets.md`,
`docs/configuration.md` and `llms.txt` are written from what the server registers, the
environment variable table in `env_vars.py` and the docs' own titles, so none of them is
edited by hand. Tool collection runs in its own process with every capability reported
present, so the output does not depend on what this host has attached. `--check` exits 1 when
a committed copy differs.
"""

from __future__ import annotations

import asyncio
import dataclasses
import difflib
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any

BEGIN = "<!-- BEGIN GENERATED TOOLSETS: `meshtastic-mcp docs generate` -->"
END = "<!-- END GENERATED TOOLSETS -->"
TABLE_BEGIN = "<!-- BEGIN GENERATED GROUPS: `meshtastic-mcp docs generate` -->"
TABLE_END = "<!-- END GENERATED GROUPS -->"

_HINTS = (
    ("readOnlyHint", "read-only"),
    ("destructiveHint", "destructive"),
    ("idempotentHint", "idempotent"),
    ("openWorldHint", "open world"),
)


def _collect() -> list[dict[str, Any]]:
    """Every tool the server can register, as plain data. Runs in the child process."""
    os.environ["MESHTASTIC_MCP_TOOLSETS"] = "all,legacy"
    os.environ["MESHTASTIC_MCP_DATA_DIR"] = tempfile.mkdtemp(prefix="mtmcp-docs-")
    os.environ.pop("MESHTASTIC_MCP_READ_ONLY", None)
    from . import capabilities

    real = capabilities.detect()
    every = dataclasses.replace(
        real, **{f.name: True for f in dataclasses.fields(real) if f.type in (bool, "bool")}
    )
    capabilities.detect = lambda: every
    from . import server, toolsets

    out = []
    for tool in asyncio.run(server.app.list_tools()):
        ann = tool.annotations
        out.append(
            {
                "name": tool.name,
                "toolset": toolsets.toolset_of(tool.name),
                "description": (tool.description or "").strip(),
                "parameters": tool.parameters or {},
                "hints": [
                    label for attr, label in _HINTS if ann is not None and getattr(ann, attr, None)
                ],
            }
        )
    return sorted(out, key=lambda t: (t["toolset"], t["name"]))


def _type(schema: dict[str, Any]) -> str:
    if "anyOf" in schema:
        kinds = [_type(s) for s in schema["anyOf"] if s.get("type") != "null"]
        return " | ".join(kinds) or "any"
    if "enum" in schema:
        return " | ".join(f"`{v}`" for v in schema["enum"])
    kind = schema.get("type", "any")
    if kind == "array":
        return f"list of {_type(schema.get('items', {}))}"
    return str(kind)


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def _group_order(tools: list[dict[str, Any]]) -> list[str]:
    groups = sorted({t["toolset"] for t in tools})
    head = [g for g in ("core",) if g in groups]
    tail = [g for g in ("legacy",) if g in groups]
    return head + [g for g in groups if g not in head + tail] + tail


def render_reference(tools: list[dict[str, Any]]) -> str:
    lines = [
        "# Tool reference",
        "",
        "Generated by `meshtastic-mcp docs generate` from the registered tools; do not edit.",
        "A tool's description and parameters here are the ones the model sees. Tools outside",
        "`core` register only when their capability is present (`doctor` says which), and",
        "`MESHTASTIC_MCP_TOOLSETS` picks the groups a session sees; `legacy` comes only when",
        "named.",
        "",
    ]
    for group in _group_order(tools):
        lines += [f"## {group}", ""]
        for tool in (t for t in tools if t["toolset"] == group):
            lines += [f"### `{tool['name']}`", ""]
            if tool["hints"]:
                lines += [", ".join(tool["hints"]).capitalize() + ".", ""]
            lines += [tool["description"], ""]
            props = tool["parameters"].get("properties", {})
            required = set(tool["parameters"].get("required", []))
            if props:
                lines += [
                    "| Parameter | Type | Default | Description |",
                    "| --- | --- | --- | --- |",
                ]
                for name, schema in props.items():
                    default = (
                        "required"
                        if name in required
                        else f"`{json.dumps(schema['default'])}`"
                        if "default" in schema
                        else ""
                    )
                    lines.append(
                        f"| `{name}` | {_cell(_type(schema))} | {default} | "
                        f"{_cell(schema.get('description', ''))} |"
                    )
                lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def render_toolsets(tools: list[dict[str, Any]]) -> str:
    rows = ["| Toolset | Tools |", "| --- | --- |"]
    for group in _group_order(tools):
        names = ", ".join(
            f"[`{t['name']}`](docs/tools.md#{t['name']})" for t in tools if t["toolset"] == group
        )
        rows.append(f"| `{group}` | {names} |")
    return "\n".join(rows)


def render_group_table(tools: list[dict[str, Any]]) -> str:
    from . import toolsets

    rows = ["| Group | Exposed | What it holds | Tools |", "| --- | --- | --- | --- |"]
    for group in _group_order(tools):
        exposed = (
            "when named"
            if group == toolsets.LEGACY
            else "with `all`"
            if group in toolsets.OPT_IN
            else "by default"
        )
        names = ", ".join(
            f"[`{t['name']}`](tools.md#{t['name']})" for t in tools if t["toolset"] == group
        )
        if group == toolsets.LEGACY:
            names = "[listed in tools.md](tools.md#legacy)"
        rows.append(
            f"| `{group}` | {exposed} | {_cell(toolsets.SUMMARIES.get(group, ''))} | {names} |"
        )
    return "\n".join(rows)


def render_configuration() -> str:
    from .env_vars import ENV_VARS, SECTIONS

    lines = [
        "# Configuration",
        "",
        "Generated by `meshtastic-mcp docs generate` from `env_vars.py`; do not edit. These are",
        "every environment variable the package reads. Set them in the MCP client's server entry",
        "(`env`), or in the environment of `meshtastic-mcp serve` on a shared bench. The server",
        "reads them when it starts, so restart it after a change.",
        "",
    ]
    for section in SECTIONS:
        rows = [v for v in ENV_VARS if v.section == section]
        if not rows:
            continue
        lines += [f"## {section}", "", "| Variable | Effect |", "| --- | --- |"]
        lines += [f"| `{v.name}` | {_cell(v.description)} |" for v in rows]
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


_LLMS_HEAD = """# meshtastic-mcp

> An MCP server and agent skills for discovering, driving, observing and testing Meshtastic
> radios and the apps that talk to them. A few intent tools (`devices`, `inspect`,
> `configure`, `send`, `admin`, `install`, `query`, `sim`, `app`) cover most work; specialist
> groups add more. Run `meshtastic-mcp doctor` to see what this host can do.

Generated by `meshtastic-mcp docs generate`; do not edit.
"""


def _summary(path: Path) -> str:
    """A page's title, or its first sentence when the title alone says little."""
    title = ""
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("# "):
            title = line[2:].strip()
            break
    return title or path.stem


def _skill_summary(path: Path) -> str:
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("description:"):
            text = line.split(":", 1)[1].strip().strip("'\"")
            return text.split(". ")[0].rstrip(".")
    return path.parent.name


def render_llms(root: Path) -> str:
    lines = [_LLMS_HEAD, "## Docs", ""]
    top = [
        ("README.md", "install, quick start and the tool groups"),
        ("AGENTS.md", "architecture and rules for agents changing this repo"),
        ("CONTRIBUTING.md", "setup, gates and releasing"),
        ("SECURITY.md", "confirmation, prompt injection and elevated-risk tools"),
    ]
    lines += [f"- [{name}]({name}): {text}" for name, text in top if (root / name).exists()]
    for page in sorted((root / "docs").glob("*.md")):
        lines.append(f"- [docs/{page.name}](docs/{page.name}): {_summary(page)}")
    skills = sorted((root / "src" / "meshtastic_mcp" / "skills").glob("*/SKILL.md"))
    if skills:
        lines += ["", "## Skills", ""]
        for skill in skills:
            rel = skill.relative_to(root).as_posix()
            lines.append(f"- [{skill.parent.name}]({rel}): {_skill_summary(skill)}")
    return "\n".join(lines).rstrip() + "\n"


def _splice(text: str, block: str, begin: str = BEGIN, end_mark: str = END) -> str:
    start, end = text.find(begin), text.find(end_mark)
    if start < 0 or end < start:
        raise SystemExit(f"no {begin} ... {end_mark} block")
    return text[: start + len(begin)] + "\n" + block + "\n" + text[end:]


def outputs(root: Path, tools: list[dict[str, Any]]) -> dict[Path, str]:
    readme = root / "README.md"
    toolsets_md = root / "docs" / "toolsets.md"
    return {
        root / "docs" / "tools.md": render_reference(tools),
        root / "docs" / "configuration.md": render_configuration(),
        readme: _splice(readme.read_text(encoding="utf-8"), render_toolsets(tools)),
        toolsets_md: _splice(
            toolsets_md.read_text(encoding="utf-8"),
            render_group_table(tools),
            TABLE_BEGIN,
            TABLE_END,
        ),
        root / "llms.txt": render_llms(root),
    }


def generate(root: Path, check: bool) -> int:
    """Run the collection in a fresh process, then write or compare the outputs."""
    proc = subprocess.run(
        [sys.executable, "-m", "meshtastic_mcp.docs_gen", "--collect"],
        capture_output=True,
        text=True,
        check=True,
    )
    tools = json.loads(proc.stdout.strip().splitlines()[-1])
    stale = []
    for path, content in outputs(root, tools).items():
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if current == content:
            continue
        if check:
            stale.append(path)
            diff = difflib.unified_diff(
                current.splitlines(), content.splitlines(), str(path), "generated", lineterm=""
            )
            print("\n".join(list(diff)[:40]), file=sys.stderr)
        else:
            path.write_text(content, encoding="utf-8")
            print(f"wrote {path.relative_to(root)}")
    if stale:
        names = ", ".join(str(p.relative_to(root)) for p in stale)
        print(f"{names} out of date; run `meshtastic-mcp docs generate`", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__" and sys.argv[1:] == ["--collect"]:
    print(json.dumps(_collect()))
